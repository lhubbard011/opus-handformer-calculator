"""The static site's in-page model (engine.js + local-api.js) must match the server.

Exports the model with tools/export_web.py, answers the same visualizer
requests with Node and with ``Runner``, and compares: generated bytes must be
identical; every number must agree to float tolerance (the JS engine sums in a
different order, so the last bits differ).

Skipped when ``node`` is not on PATH.
"""

import json
import logging
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

import numpy as np

from handformer.viz.runner import Runner

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import export_web  # noqa: E402

log = logging.getLogger(__name__)
NODE = shutil.which("node")
EXPRESSIONS = ["7+5", "-12.5*3-4", "(2+3)^3/7~3", "1-999", "2^-2"]
TOL = 1e-6


def close(a, b, what):
    a, b = np.asarray(a, dtype=np.float64), np.asarray(b, dtype=np.float64)
    if a.shape != b.shape:
        raise AssertionError(f"{what}: shape {a.shape} vs {b.shape}")
    err = np.abs(a - b) / np.maximum(1.0, np.abs(b))
    if err.size and err.max() > TOL:
        i = np.unravel_index(int(err.argmax()), err.shape)
        raise AssertionError(f"{what}: at {i} js={a[i]!r} py={b[i]!r}")


def close_dict(a: dict, b: dict, what):
    keys = set(a) | set(b)
    for k in keys:
        close(a.get(k, 0.0), b.get(k, 0.0), f"{what}[{k}]")


@unittest.skipIf(NODE is None, "node not installed")
class TestWebParity(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.runner = Runner()
        cls.tmp = Path(tempfile.mkdtemp(prefix="handformer-web-"))
        export_web.export(cls.tmp)

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.tmp, ignore_errors=True)

    def node(self, requests: list, model_dir: Path | None = None) -> list:
        req, out = self.tmp / "req.json", self.tmp / "out.json"
        req.write_text(json.dumps(requests))
        proc = subprocess.run([NODE, "--experimental-detect-module", "--no-warnings", str(ROOT / "tests/web_parity.mjs"),
                               str(model_dir or self.tmp), str(req), str(out)], capture_output=True, text=True, timeout=600)
        log.info("node exited %d: %s", proc.returncode, proc.stdout.strip().splitlines()[-1:] )
        self.assertEqual(proc.returncode, 0, proc.stderr)
        return json.loads(out.read_text())

    def test_info_is_server_info(self):
        self.assertEqual(json.loads((self.tmp / "info.json").read_text()),
                         json.loads(json.dumps(self.runner.info())))

    def test_runs_match(self):
        r = self.runner
        for expression in EXPRESSIONS:
            with self.subTest(expression=expression):
                py = r.run(expression)
                n = len(py["chars"])
                qs = sorted({py["prompt_len"] - 1, n // 2, n - 2})
                reqs = [["/api/run", {"expression": expression}]]
                reqs += [["/api/position", {"run_id": "$run", "q": q}] for q in qs]
                reqs += [["/api/attention", {"run_id": "$run", "layer": 4, "head": 0}],
                         ["/api/residual", {"run_id": "$run", "snapshot": 21}],
                         ["/api/mlp", {"run_id": "$run", "layer": 3}]]
                js = self.node(reqs)
                run = js[0]
                self.assertNotIn("error", run, run)
                self.assertEqual(run["chars"], py["chars"])
                for key in ("model_id", "expression", "prompt_len", "finished", "snapshots"):
                    self.assertEqual(run[key], py[key], key)
                for q, (a, b) in enumerate(zip(run["steps"], py["steps"])):
                    self.assertEqual(a["pred"], b["pred"], f"pred at {q}")
                    close_dict(a["v"], b["v"], f"step {q}")

                rid = py["run_id"]
                for q, jp in zip(qs, js[1:1 + len(qs)]):
                    pp = r.position(rid, q)
                    close(jp["values"], pp["values"], f"values q={q}")
                    self.assertEqual([lg[0] for lg in jp["logits"]][:1], [lg[0] for lg in pp["logits"]][:1])
                    close([lg[1] for lg in jp["logits"]], [lg[1] for lg in pp["logits"]], f"logits q={q}")
                    for hj, hp in zip(jp["heads"], pp["heads"]):
                        close_dict(hj["wrote"], hp["wrote"], f"head L{hp['layer']}h{hp['head']} wrote q={q}")
                        close([w for _, w in hj["top"]], [w for _, w in hp["top"]], f"top weights q={q}")
                        ws = [w for _, w in hp["top"]]
                        for i, (kj, kp) in enumerate(zip(hj["top"], hp["top"])):
                            if ws[i] > 1e-6 and all(abs(ws[i] - w) > 1e-6 for t, w in enumerate(ws) if t != i):  # untied, non-negligible
                                self.assertEqual(kj[0], kp[0], f"top key rank {i} q={q} L{hp['layer']}h{hp['head']}: js {hj['top']} py {hp['top']}")
                    self.assertEqual({(u["layer"], u["unit"]) for u in jp["units"]},
                                     {(u["layer"], u["unit"]) for u in pp["units"]}, f"active units q={q}")

                k = 1 + len(qs)
                for j, (mat, meta) in zip(js[k:], [r.attention_map(rid, 4, 0), r.residual_map(rid, 21), r.mlp_map(rid, 3)]):
                    self.assertEqual(j["meta"]["shape"], list(mat.shape))
                    # Compare un-normalised values: a row whose max is float noise (~1e-7)
                    # normalises noise to ±1, and noise differs with summation order.
                    # Rows whose scale rounds to 0 are pure float noise on both sides: skipped.
                    scale = np.array(meta.get("scale", np.ones(mat.shape[0])))[:, None]
                    scale = np.where(scale > 0, scale, 0.0)
                    close(np.array(j["data"]).reshape(mat.shape) * scale, mat.astype(np.float32) * scale, f"map {meta}")
                    if "scale" in meta:
                        close(j["meta"]["scale"], meta["scale"], "scale")

    def test_knockouts_match(self):
        """Knocked-out heads, units and dims: same bytes and traces in both engines."""
        r = self.runner
        ko = {"heads": [[4, 0]], "units": [[3, 11], [3, 12]], "dims": ["add.carry"]}
        # A knockout that breaks the model: it never writes '\n', so both engines cap the run at the
        # same length. Its bytes come from near-tied logits (float summation order decides), so
        # byte-exact parity is not meaningful there; length and "did not finish" are.
        broken = {"units": [[0, 6]]}
        py = r.run("47+38", broken)
        js = self.node([["/api/run", {"expression": "47+38", "knockout": broken}]])
        self.assertFalse(py["finished"])
        self.assertFalse(js[0]["finished"])
        self.assertEqual(len(js[0]["chars"]), len(py["chars"]))
        self.assertLess(len(py["chars"]), 200, "a broken run must be capped near the normal answer length")
        for expression in ("47+38", "12*34-5"):
            with self.subTest(expression=expression):
                py = r.run(expression, ko)
                q = len(py["chars"]) // 2
                js = self.node([["/api/run", {"expression": expression, "knockout": ko}],
                                ["/api/position", {"run_id": "$run", "q": q}]])
                self.assertNotIn("error", js[0], js[0])
                self.assertEqual(js[0]["chars"], py["chars"])
                self.assertEqual(js[0]["knockout"], py["knockout"])
                close(js[1]["values"], r.position(py["run_id"], q)["values"], f"knockout values q={q}")
        bad = self.node([["/api/run", {"expression": "1+1", "knockout": {"dims": ["pos"]}}]])
        self.assertIn("cannot be knocked out", bad[0]["error"])

    def test_life_matches(self):
        """The Game of Life model: same bytes, step values and traces in both engines (and a knockout)."""
        life_dir = self.tmp / "life"
        export_web.export(life_dir, "life")
        r = Runner("life")
        for text, ko in (("3:.#./.#./.#.", None), ("2:....../..#.../...#../.###../....../......", None),
                         ("2:###/#../.#.", {"units": [[1, 3]]})):
            with self.subTest(text=text, ko=ko):
                py = r.run(text, ko)
                q = len(py["chars"]) // 2
                req = [["/api/run", {"expression": text, **({"knockout": ko} if ko else {})}], ["/api/position", {"run_id": "$run", "q": q}]]
                js = self.node(req, life_dir)
                self.assertNotIn("error", js[0], js[0])
                self.assertEqual(js[0]["chars"], py["chars"])
                for a, b in zip(js[0]["steps"], py["steps"]):
                    self.assertEqual(a["pred"], b["pred"])
                    close_dict(a["v"], b["v"], "life step")
                close(js[1]["values"], r.position(py["run_id"], q)["values"], f"life values q={q}")
        bad = self.node([["/api/run", {"expression": ".#./###"}]], life_dir)
        self.assertIn("start with the number of generations", bad[0]["error"])

    def test_c_matches(self):
        """The C highlighter: same letters, step values and traces in both engines (spaces and newlines kept)."""
        c_dir = self.tmp / "c"
        export_web.export(c_dir, "c")
        r = Runner("c")
        for src in ('int main(void) { /* hi */\n  return 0x1F; // x\n}\n', '#define S "a\\"b" \\\n  more\nchar c = \'\\n\';'):
            with self.subTest(src=src):
                py = r.run(src)
                q = len(py["chars"]) - 3
                js = self.node([["/api/run", {"expression": src}], ["/api/position", {"run_id": "$run", "q": q}]], c_dir)
                self.assertNotIn("error", js[0], js[0])
                self.assertEqual(js[0]["chars"], py["chars"])
                self.assertEqual(js[0]["expression"], src)
                for a, b in zip(js[0]["steps"], py["steps"]):
                    self.assertEqual(a["pred"], b["pred"])
                    close_dict(a["v"], b["v"], "c step")
                close(js[1]["values"], r.position(py["run_id"], q)["values"], f"c values q={q}")
        bad = self.node([["/api/run", {"expression": "int\x01x;"}]], c_dir)
        self.assertIn("unsupported characters", bad[0]["error"])

    def test_weights_match(self):
        r = self.runner
        cases = [("embed", None, None), ("unembed", None, None), ("wq", 4, 0), ("wk", 2, 1), ("wov", 7, 2),
                 ("w_in", 3, None), ("w_out", 12, None)]
        js = self.node([["/api/weights", {"kind": k, "layer": l, "head": h, "trim": t}]
                        for k, l, h in cases for t in (True, False)])
        for (kind, layer, head), trim, j in zip([c for c in cases for _ in (0, 1)], [True, False] * len(cases), js):
            with self.subTest(kind=kind, trim=trim):
                mat, meta = r.weights(kind, layer, head, trim)
                for key in ("title", "rows", "cols", "full_shape", "nonzero"):
                    self.assertEqual(j["meta"][key], meta[key], key)
                close(np.array(j["data"]).reshape(mat.shape), mat.astype(np.float32), kind)

    def test_errors_match(self):
        js = self.node([["/api/run", {"expression": "2+x"}], ["/api/run", {"expression": "="}]])
        self.assertIn("unsupported characters: 'x'", js[0]["error"])
        self.assertIn("empty expression", js[1]["error"])


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    unittest.main()
